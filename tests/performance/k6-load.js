/**
 * tests/performance/k6-load.js — k6 load test for wiki.js.
 * Run: k6 run --env TARGET_URL=http://wiki.production.svc.cluster.local:3000 k6-load.js
 */
import http from 'k6/http'
import { check, sleep, group } from 'k6'
import { Rate, Trend } from 'k6/metrics'

const TARGET = __ENV.TARGET_URL || 'http://localhost:3000'
const DURATION = __ENV.DURATION || '60s'
const VUS = parseInt(__ENV.VUS || '50', 10)

// Custom metrics
const pageCreateFailRate = new Rate('page_create_fail_rate')
const healthLatency = new Trend('health_latency_ms', true)

export const options = {
  scenarios: {
    browse: {
      executor: 'ramping-vus',
      exec: 'browse',
      startVUs: 0,
      stages: [
        { duration: '10s', target: VUS },
        { duration: DURATION, target: VUS },
        { duration: '10s', target: 0 }
      ],
      gracefulRampDown: '10s'
    },
    write: {
      executor: 'constant-vus',
      exec: 'writePages',
      vus: 5,
      duration: DURATION
    }
  },
  thresholds: {
    // SLO: p95 latency < 200ms, error rate < 1%
    http_req_duration: ['p(95)<200'],
    http_req_failed: ['rate<0.01'],
    page_create_fail_rate: ['rate<0.05']
  }
}

export default function () {
  // Browse scenario: read public endpoints
  group('browse', () => browse())
}

export function browse() {
  const r1 = http.get(`${TARGET}/health/live`)
  check(r1, { 'live 200': (r) => r.status === 200 })
  healthLatency.add(r1.timings.waiting)

  const r2 = http.get(`${TARGET}/api/pages`)
  check(r2, { 'list 200': (r) => r.status === 200 })

  sleep(0.5)
}

export function writePages() {
  const slug = `perf-${Date.now()}-${__VU}-${__ITER}`
  const payload = JSON.stringify({
    slug,
    title: `Perf ${__ITER}`,
    content: `# Perf\nGenerated by k6 vus=${__VU} iter=${__ITER}`
  })
  const params = { headers: { 'Content-Type': 'application/json' } }
  const r = http.post(`${TARGET}/api/pages`, payload, params)
  const ok = check(r, { 'create 201': (res) => res.status === 201 })
  pageCreateFailRate.add(!ok)
}

export function handleSummary(data) {
  return {
    stdout: textSummary(data),
    '/tmp/k6-summary.json': JSON.stringify(data, null, 2)
  }
}

// Compact summary
function textSummary(data) {
  const m = data.metrics
  const dur = m.http_req_duration
  const failed = m.http_req_failed
  return `
═══ k6 Performance Summary ═══
Total requests:  ${m.http_reqs.values.count}
Duration:        ${data.state.testRunDurationMs}ms
─────────────────────────────────
http_req_duration:
  avg:   ${dur.values.avg.toFixed(2)} ms
  p(50): ${dur.values['p(50)'].toFixed(2)} ms
  p(95): ${dur.values['p(95)'].toFixed(2)} ms
  p(99): ${dur.values['p(99)'].toFixed(2)} ms
http_req_failed:  ${(failed.values.rate * 100).toFixed(2)}%
checks passed:    ${data.metrics.checks.values.passes}/${data.metrics.checks.values.passes + data.metrics.checks.values.fails}
`
}
